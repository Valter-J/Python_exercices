# Um dos tipos de coleções em Python é a lista. Listas são ordenadas,
#  mutáveis, e permitem valores duplicados. Para criar uma lista basta
#  declarar uma variável inicializando-a com os valores entre [ ]. Cada 
# elemento dentro da lista é separado por virgulas.

frutas = ["Banana", "Laranja", "Maçã", "Manga"]
contatinhos = ["José", "Vitor", "André", "Fabio"]

# Você pode imprimir uma variável lista


print(frutas)
print(contatinhos)

# Ou imprimir cada um de seus elementos



print(frutas[1])
print(frutas[3])
print(frutas[4])
